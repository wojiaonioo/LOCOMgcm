#: Every obsolete name and the name that replaced it.
LEGACY_ENV_NAMES: dict[str, str] = {**_SHORT_PREFIX, **_LONG_PREFIX}
#: Path, identity and logging names with only long-prefix legacy aliases.
#: Exclude these from DEFGCM_* when selecting numerical switches.
LONG_PREFIX_NAMES = frozenset(_LONG_PREFIX.values()) - frozenset(_SHORT_PREFIX.values())


def reject_legacy_environment(environ: Mapping[str, str] = os.environ) -> None:
    """Raise RuntimeError listing every obsolete name set in ``environ`` with its replacement."""
    found = [f"{old} -> {new}" for old, new in LEGACY_ENV_NAMES.items() if old in environ]
    if found:
        raise RuntimeError("obsolete environment variables are set; "
                           "set the new names: " + "; ".join(found))
