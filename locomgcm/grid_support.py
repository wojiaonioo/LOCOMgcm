"""Grid-topology capability matrix — single source.

Each registrable component class declares which grid topologies it works on
via a ``grid_support`` CLASS attribute (tuple of topology names).  The
declaration lives ON the class, next to the code it describes, so a new
component's change necessarily carries its topology claim (contract text
lives with the code, not in a standalone table that rots).

Default is ``("latlon",)`` — conservative: an undeclared component is
regional-only until someone proves it on the cube (bitwise against the
regional path) and declares it.

``grid_support`` is a CAPABILITY claim ("assembled on this topology, the
component produces correct numbers"), not a POLICY gate.  Policy gates —
the cube path rejecting boundary-condition blocks (closed global domain),
the cube path accepting only the implicit_free_surface
stepper NAME — stay where they are; they restrict beyond capability.

Consumers of the runtime declarations:
  * runtime raise — the cube runtime's dynamics whitelist derives from
    :func:`cube_dynamics_names`; the model's cube-stepper guard reads the
    stepper class's declaration;
  * user docs — the markdown matrix is generated by
    :func:`format_grid_support_table`;
  * webui — ``ParamEntry.grid_support`` uses the same vocabulary.
"""
from __future__ import annotations

SUPPORTED_TOPOLOGIES: tuple[str, ...] = ("latlon", "cube")

# The conservative default for components that carry no declaration.
DEFAULT_GRID_SUPPORT: tuple[str, ...] = ("latlon",)


def component_grid_support(cls: type) -> tuple[str, ...]:
    """Read a component class's ``grid_support`` declaration (with default)."""
    support = tuple(getattr(cls, "grid_support", DEFAULT_GRID_SUPPORT))
    bad = [t for t in support if t not in SUPPORTED_TOPOLOGIES]
    if bad:
        raise ValueError(
            f"{cls.__name__}.grid_support has illegal topology value(s) {bad!r}; "
            f"allowed = {list(SUPPORTED_TOPOLOGIES)}"
        )
    if not support:
        raise ValueError(f"{cls.__name__}.grid_support must not be empty")
    return support


def grid_support_matrix() -> dict[str, dict[str, tuple[str, ...]]]:
    """The full (component x topology) matrix, derived from the registries.

    Imports inside the function so importing this module stays cheap and the
    registries' eager-registration side effects fire only when the matrix is
    actually built.
    """
    import locomgcm.boundaries  # noqa: F401 — eager registration
    import locomgcm.dynamics  # noqa: F401
    import locomgcm.steppers  # noqa: F401
    from locomgcm.boundaries._registry import BOUNDARY_CONDITIONS
    from locomgcm.dynamics._registry import DYNAMICS_MODULES
    from locomgcm.steppers._registry import STEPPERS

    matrix: dict[str, dict[str, tuple[str, ...]]] = {}
    for kind, registry in (
        ("dynamics", DYNAMICS_MODULES),
        ("stepper", STEPPERS),
        ("boundary_condition", BOUNDARY_CONDITIONS),
    ):
        matrix[kind] = {
            name: component_grid_support(registry.get(name))
            for name in sorted(registry.items())
        }
    return matrix


def cube_dynamics_names() -> frozenset[str]:
    """Dynamics module names declared cube-capable (the cube-yaml whitelist)."""
    return frozenset(
        name
        for name, support in grid_support_matrix()["dynamics"].items()
        if "cube" in support
    )


def format_grid_support_table() -> str:
    """Render the matrix as the markdown document (docs drift-gate source)."""
    matrix = grid_support_matrix()
    lines = [
        "# Grid-support matrix — (component × topology)",
        "",
        "> GENERATED by `locomgcm.grid_support.format_grid_support_table()`;",
        "> do not edit by hand; it is rendered from the runtime declarations.",
        ">",
        "> `grid_support` is a capability claim (assembled on that topology, the",
        "> component produces correct numbers), not a policy gate: the cube path",
        "> additionally rejects boundary-condition blocks (closed global domain)",
        "> and accepts only the `implicit_free_surface` stepper name.",
        "",
    ]
    for kind, rows in matrix.items():
        lines.append(f"## {kind}")
        lines.append("")
        lines.append("| name | latlon | cube |")
        lines.append("|---|---|---|")
        for name, support in rows.items():
            latlon = "✅" if "latlon" in support else "—"
            cube = "✅" if "cube" in support else "—"
            lines.append(f"| `{name}` | {latlon} | {cube} |")
        lines.append("")
    return "\n".join(lines)
